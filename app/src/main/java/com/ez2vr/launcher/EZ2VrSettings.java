package com.ez2vr.launcher;

import android.content.Context;
import android.content.SharedPreferences;
import java.io.File;
import java.io.FileOutputStream;
import java.nio.charset.StandardCharsets;
import java.util.Locale;

/**
 * Player-owned VR settings.
 *
 * <p>Counterpart of the menu authorities behind SourceVR's vr_* table: the menu
 * (EZ2VrSettingsActivity) owns these values, persists them in SharedPreferences
 * (which plays config.cfg's role), and the engine launch appends them as
 * {@code +convar value} pairs AFTER the overlay cfgs — so player choice always
 * beats boot defaults. Overlay files must never duplicate these keys as ACTIVE
 * rows (see ez2vr_boot.cfg header).
 */
public final class EZ2VrSettings {
    private static final String PREFS = "ez2vr_settings";

    public static final String KEY_LOCOMOTION = "ez2vr_locomotion_mode"; // 0 smooth 1 teleport 2 dash
    public static final String KEY_TURN = "ez2vr_turn_mode"; // 0 snap 1 smooth
    public static final String KEY_SEATED = "ez2vr_seated"; // 0/1
    public static final String KEY_VISOR = "ez2vr_visor_overlay"; // 0/1
    public static final String KEY_FLASHLIGHT_MOUNT = "ez2vr_flashlight_mount"; // 0 hand 1 head
    public static final String KEY_VEHICLE_AIM = "ez2vr_vehicle_aim_mode"; // 0 head 1 hand
    public static final String KEY_PERF_MODE = "ez2vr_performance_mode"; // 0 quality 1 balanced 2 perf
    public static final String KEY_FFR = "ez2vr_ffr_level"; // 0..3

    /** Authored snapshot in the write game dir; guarded by
     * {@link EZ2ContentPaths#writeGameCfg} against the retail leaves. */
    private static final String USER_CFG_NAME = "ez2vr_user.cfg";

    private EZ2VrSettings() {}

    private static SharedPreferences prefs(Context ctx) {
        return ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
    }

    public static int locomotion(Context ctx) { return prefs(ctx).getInt(KEY_LOCOMOTION, 0); }
    public static int turn(Context ctx) { return prefs(ctx).getInt(KEY_TURN, 0); }
    public static boolean seated(Context ctx) { return prefs(ctx).getBoolean(KEY_SEATED, false); }
    public static boolean visor(Context ctx) { return prefs(ctx).getBoolean(KEY_VISOR, true); }
    public static int flashlightMount(Context ctx) { return prefs(ctx).getInt(KEY_FLASHLIGHT_MOUNT, 0); }
    public static int vehicleAim(Context ctx) { return prefs(ctx).getInt(KEY_VEHICLE_AIM, 0); }
    public static int perfMode(Context ctx) { return prefs(ctx).getInt(KEY_PERF_MODE, 0); }
    public static int ffr(Context ctx) { return prefs(ctx).getInt(KEY_FFR, 0); }

    public static void save(Context ctx, int locomotion, int turn, boolean seated,
                            boolean visor, int flashlightMount, int vehicleAim,
                            int perfMode, int ffr) {
        prefs(ctx).edit()
                .putInt(KEY_LOCOMOTION, locomotion)
                .putInt(KEY_TURN, turn)
                .putBoolean(KEY_SEATED, seated)
                .putBoolean(KEY_VISOR, visor)
                .putInt(KEY_FLASHLIGHT_MOUNT, flashlightMount)
                .putInt(KEY_VEHICLE_AIM, vehicleAim)
                .putInt(KEY_PERF_MODE, perfMode)
                .putInt(KEY_FFR, ffr)
                .apply();
    }

    /**
     * Player overrides as engine command-line pairs. Appended AFTER the overlay
     * +execs so they win over boot defaults on every launch.
     */
    public static String buildExtraArgs(Context ctx) {
        return String.format(Locale.US,
                "+%s %d +%s %d +%s %d +%s %d +%s %d +%s %d +%s %d +%s %d",
                KEY_LOCOMOTION, locomotion(ctx),
                KEY_TURN, turn(ctx),
                KEY_SEATED, seated(ctx) ? 1 : 0,
                KEY_VISOR, visor(ctx) ? 1 : 0,
                KEY_FLASHLIGHT_MOUNT, flashlightMount(ctx),
                KEY_VEHICLE_AIM, vehicleAim(ctx),
                KEY_PERF_MODE, perfMode(ctx),
                KEY_FFR, ffr(ctx));
    }

    /**
     * Writes a debuggable snapshot of the same values into the write game dir.
     * The engine does not need to exec it (command line already carries them);
     * it exists so bug reports can attach one file with the full posture.
     * It lives under the write game dir, which the engine no longer reads now
     * that VALVE_GAME_PATH is the content root, so it is diagnostic-only.
     */
    public static File writeUserCfg(Context ctx) throws Exception {
        File out = EZ2ContentPaths.writeGameCfg(ctx, USER_CFG_NAME);
        File dir = out.getParentFile();
        if (dir != null && !dir.isDirectory() && !dir.mkdirs() && !dir.isDirectory()) {
            throw new IllegalStateException("cannot create " + dir);
        }
        StringBuilder sb = new StringBuilder(
                "// generated by EZ2 VR Settings — do not hand-edit; use the menu\n");
        appendLine(sb, KEY_LOCOMOTION, locomotion(ctx));
        appendLine(sb, KEY_TURN, turn(ctx));
        appendLine(sb, KEY_SEATED, seated(ctx) ? 1 : 0);
        appendLine(sb, KEY_VISOR, visor(ctx) ? 1 : 0);
        appendLine(sb, KEY_FLASHLIGHT_MOUNT, flashlightMount(ctx));
        appendLine(sb, KEY_VEHICLE_AIM, vehicleAim(ctx));
        appendLine(sb, KEY_PERF_MODE, perfMode(ctx));
        appendLine(sb, KEY_FFR, ffr(ctx));
        try (FileOutputStream fos = new FileOutputStream(out, false)) {
            fos.write(sb.toString().getBytes(StandardCharsets.UTF_8));
            fos.flush();
            fos.getFD().sync();
        }
        return out;
    }

    private static void appendLine(StringBuilder sb, String key, int value) {
        sb.append(key).append(" \"").append(value).append("\"\n");
    }
}
